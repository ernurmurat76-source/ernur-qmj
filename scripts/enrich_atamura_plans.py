def main() -> int:
    path = Path(sys.argv[1] if len(sys.argv) > 1 else "data/qmj-reference-index.json")
    data = json.loads(path.read_text(encoding="utf-8"))
    enriched = 0
    visual_count = 0
    families: dict[str, int] = {}
    for record in data.get("records", []):
        if record.get("term") not in {2, 3, 4} or record.get("source", {}).get("status") != "teacher-provided-ktz":
            continue
        plan = build_plan(record)
        record["prepared_plan"] = plan
        record["textbook_alignment"] = {
            "publisher": "Атамұра",
            "books": plan["textbookSources"],
            "use": "section-and-topic-alignment",
            "content_policy": "original-tasks-no-textbook-page-redistribution",
        }
        flags = [f for f in record.get("quality_flags", []) if not f.startswith("atamura_")]
        flags.extend(["prepared_45_minute_plan_no_runtime_ai", "atamura_topic_aligned", "original_concrete_tasks"])
        if plan["visuals"]:
            flags.append("atamura_visual_support")
            visual_count += 1
        record["quality_flags"] = list(dict.fromkeys(flags))
        families[plan["family"]] = families.get(plan["family"], 0) + 1
        enriched += 1

    data["prepared_plan_count"] = enriched
    data["visual_plan_count"] = visual_count
    data["runtime_ai_policy"] = "term 2-4 prepared records render directly without an AI API call"
    data["textbook_alignment"] = "supplied Atamura editions; original tasks and diagrams"
    data["version"] = "12-atamura-enriched"
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"enriched": enriched, "with_visuals": visual_count, "families": families}, ensure_ascii=False, indent=2))
    return 0 if enriched else 1


if __name__ == "__main__":
    raise SystemExit(main())
