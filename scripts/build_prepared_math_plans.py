def main() -> int:
    path = Path(sys.argv[1] if len(sys.argv) > 1 else "data/qmj-reference-index.json")
    data = json.loads(path.read_text(encoding="utf-8"))
    built = 0
    families: Counter[str] = Counter()
    for record in data.get("records", []):
        if record.get("term") in {2, 3, 4} and record.get("source", {}).get("status") == "teacher-provided-ktz":
            plan = build_plan(record)
            record["prepared_plan"] = plan
            record["quality_flags"] = [flag for flag in record.get("quality_flags", []) if flag != "curriculum_only_no_reference_flow"]
            record["quality_flags"].append("prepared_45_minute_plan_no_runtime_ai")
            built += 1
            families[plan["family"]] += 1
    data["prepared_plan_count"] = built
    data["runtime_ai_policy"] = "prepared records render directly without an AI API call"
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"prepared": built, "families": families}, ensure_ascii=False, indent=2))
    return 0 if built else 1


if __name__ == "__main__":
    raise SystemExit(main())
